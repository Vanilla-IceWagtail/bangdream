function variants(color) {
  /* 同时匹配「逗号后有空格」和「无空格」两种写法 */
  const out = [color];
  if (color.indexOf('rgba(') === 0) out.push(color.replace(/,\s*/g, ','));
  return out;
}

function main() {
  let css = fs.readFileSync(CSS, 'utf8');
  const before = css;
  let hits = 0;
  const report = [];
  MAP.forEach(([from, to]) => {
    variants(from).forEach((v) => {
      const parts = css.split(v);
      const n = parts.length - 1;
      if (n > 0) {
        css = parts.join(to);
        hits += n;
        report.push('  ' + String(n).padStart(3) + '  ' + v + '  →  ' + to);
      }
    });
  });

  console.log('替换次数：' + hits);
  report.forEach((r) => console.log(r));

  /* 复核：还有哪些硬编码颜色没被映射到 */
  const leftover = {};
  (css.replace(/\/\*[\s\S]*?\*\//g, '').match(/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g) || []).forEach((c) => {
    const k = c.replace(/\s+/g, '');
    leftover[k] = (leftover[k] || 0) + 1;
  });
  const rest = Object.entries(leftover).sort((a, b) => b[1] - a[1]);
  console.log('\n替换后剩余颜色（需要人工确认是否与亮色主题协调）：');
  rest.forEach(([c, n]) => console.log('  ' + String(n).padStart(3) + '  ' + c));

  if (dry) {
    console.log('\n（--dry：没有写回文件）');
    return;
  }
  if (css === before) {
    console.log('\n没有变化，未写回。');
    return;
  }
  fs.writeFileSync(CSS, css, 'utf8');
  console.log('\n已写回 ' + CSS);
}

main();
